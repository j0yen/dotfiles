#!/usr/bin/env python3
"""caps-digest: generate .config/fleet/caps-digest.md from .config/fleet/caps.tsv v2.

The digest is the human page for the fleet caps registry (P28 five-whys 11-01, A322):
one table per class, live rows only (verdict KEEP/CHECK/CHANGE), voided classes listed
as void. `--check` exits 1 when the committed digest differs from the generated one
(no-drift test; run on ryzen7 or in CI, never a build on carbon).
"""
import argparse, csv, io, sys
from pathlib import Path

LIVE = {"KEEP", "CHECK", "CHANGE"}
VOIDED = {"rationing", "leased-box"}
COLS = ("id", "name", "value", "host", "enforced_at", "premise", "expires", "owner")


def load(path: Path):
    rows, lines, header = [], [], None
    with path.open(encoding="utf-8") as fh:
        for l in fh:
            if header is None and l.startswith("# id\t"):
                header = l[2:]
            elif header is not None and not l.startswith("#"):
                lines.append(l)
    if header is None:
        print(f"caps-digest: {path} has no '# id' header line", file=sys.stderr)
        return [], []
    rd = csv.DictReader([header] + lines, delimiter="\t")
    for r in rd:
        if r.get("id"):
            rows.append(r)
    return rows, rd.fieldnames or []


def render(rows, src_name: str) -> str:
    by = {}
    for r in rows:
        by.setdefault(r.get("class", ""), []).append(r)
    out = io.StringIO()
    w = out.write
    live = [r for r in rows if r.get("verdict") in LIVE]
    w("# Fleet caps digest\n\n")
    w(f"Generated by caps-digest.py from {src_name}; do not edit by hand. "
      f"{len(rows)} rows, {len(live)} live. Cite a cap in prose or CLAUDE.md by its id (`C001`); "
      "the value lives only in the registry.\n\n")
    for cls in sorted(by):
        rs = by[cls]
        w(f"## {cls or '(no class)'}\n\n")
        if cls in VOIDED:
            w(f"Voided class (approvals #195, 11-01): {len(rs)} rows kept as history, no live value.\n\n")
            continue
        w("| " + " | ".join(COLS) + " | verdict |\n")
        w("|" + "---|" * (len(COLS) + 1) + "\n")
        for r in sorted(rs, key=lambda r: r["id"]):
            cells = [(r.get(c) or "").replace("|", "\\|").replace("\n", " ") for c in COLS]
            w("| " + " | ".join(cells) + f" | {r.get('verdict','')} |\n")
        w("\n")
    return out.getvalue()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("tsv", type=Path)
    ap.add_argument("out", type=Path)
    ap.add_argument("--check", action="store_true", help="exit 1 when out differs from the generated text")
    a = ap.parse_args()
    rows, fields = load(a.tsv)
    for c in ("id", "class", "verdict", "premise", "expires", "applied_by"):
        if c not in fields:
            print(f"caps-digest: {a.tsv} lacks column {c} (v2 expected)", file=sys.stderr)
            return 2
    text = render(rows, a.tsv.name)
    if a.check:
        cur = a.out.read_text(encoding="utf-8") if a.out.exists() else ""
        if cur != text:
            print(f"caps-digest: {a.out} drifted from {a.tsv}; regenerate", file=sys.stderr)
            return 1
        print(f"caps-digest: {a.out} matches ({len(rows)} rows)")
        return 0
    a.out.write_text(text, encoding="utf-8")
    print(f"caps-digest: wrote {a.out} ({len(rows)} rows)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
